-- Nuevo apartado con su anticipo
create or replace function public.registrar_apartado(p jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_cid     text := p->>'client_id';
  v_id      bigint;
  v_yo      public.perfiles%rowtype;
  v_cliente text := left(trim(coalesce(p->>'cliente','')), 60);
  v_tel     text := left(trim(coalesce(p->>'telefono','')), 20);
  v_art     text := left(trim(coalesce(p->>'articulo','')), 60);
  v_precio  numeric(12,2);
  v_ant     numeric(12,2);
  v_metodo  text := coalesce(p->>'metodo', 'efectivo');
  v_ts      timestamptz := now();
  v_dia     date := (now() at time zone 'America/Mexico_City')::date;
  v_hora    text := to_char(now() at time zone 'America/Mexico_City', 'HH24:MI');
begin
  select * into v_yo from public.perfiles where id = auth.uid() and activo;
  if not found then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if v_cid is null or v_cid !~ '^[A-Za-z0-9_-]{6,60}$' then raise exception 'Apartado sin identificador válido.'; end if;
  select id into v_id from public.apartados where client_id = v_cid;
  if found then return v_id; end if;
  if v_cliente = '' then raise exception 'Escribe el nombre de quien aparta.'; end if;
  if length(regexp_replace(v_tel, '[^0-9]', '', 'g')) < 8 then raise exception 'Escribe un teléfono de contacto (al menos 8 dígitos).'; end if;
  if v_art = '' then raise exception 'Escribe qué artículo se aparta.'; end if;
  begin
    v_precio := round((p->>'precio')::numeric, 2);
    v_ant := round((p->>'anticipo')::numeric, 2);
  exception when others then raise exception 'El precio o el anticipo no son válidos.'; end;
  if v_precio is null or v_precio <= 0 or v_precio > 10000000 then raise exception 'El precio no es válido.'; end if;
  if v_ant is null or v_ant <= 0 then raise exception 'El anticipo debe ser mayor a cero.'; end if;
  if v_ant >= v_precio then raise exception 'El anticipo cubre todo el precio: regístralo como venta normal.'; end if;
  if v_metodo not in ('efectivo','transferencia','tarjeta') then raise exception 'Forma de pago inválida.'; end if;

  insert into public.apartados (client_id, ts, dia, hora, cliente, telefono, articulo, precio, pagado, usuario, registro, registrado_por)
  values (v_cid, v_ts, v_dia, v_hora, v_cliente, v_tel, v_art, v_precio, v_ant, v_yo.usuario, v_yo.nombre, auth.uid())
  on conflict (client_id) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from public.apartados where client_id = v_cid;
    return v_id;
  end if;
  insert into public.apartado_pagos (client_id, apartado_id, tipo, monto, metodo, ts, dia, hora, usuario, registro, registrado_por)
  values (v_cid || '-a', v_id, 'anticipo', v_ant, v_metodo, v_ts, v_dia, v_hora, v_yo.usuario, v_yo.nombre, auth.uid());
  return v_id;
end $$;

-- Abono. Si con este pago se completa el precio, es el finiquito:
-- se crea la venta por el precio completo y entra al corte de ese día.
create or replace function public.abonar_apartado(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_cid     text := p->>'client_id';
  v_yo      public.perfiles%rowtype;
  v_ap      public.apartados%rowtype;
  v_apid    bigint;
  v_monto   numeric(12,2);
  v_metodo  text := coalesce(p->>'metodo', 'efectivo');
  v_saldo   numeric(12,2);
  v_tipo    text;
  v_pago    bigint;
  v_folio   bigint;
  v_metv    text;
  v_ts      timestamptz := now();
  v_dia     date := (now() at time zone 'America/Mexico_City')::date;
  v_hora    text := to_char(now() at time zone 'America/Mexico_City', 'HH24:MI');
begin
  select * into v_yo from public.perfiles where id = auth.uid() and activo;
  if not found then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if v_cid is null or v_cid !~ '^[A-Za-z0-9_-]{6,64}$' then raise exception 'Abono sin identificador válido.'; end if;
  begin v_apid := (p->>'apartado')::bigint; exception when others then v_apid := null; end;
  select * into v_ap from public.apartados where id = v_apid for update;
  if not found then raise exception 'No existe ese apartado.'; end if;

  -- Reintento de un abono que ya llegó
  select id, tipo into v_pago, v_tipo from public.apartado_pagos where client_id = v_cid;
  if found then return jsonb_build_object('pago', v_pago, 'tipo', v_tipo, 'folio', v_ap.folio_venta); end if;

  if v_ap.estado = 'liquidado' then raise exception 'Ese apartado ya está liquidado.'; end if;
  if v_ap.estado = 'cancelado' then raise exception 'Ese apartado está cancelado.'; end if;
  begin v_monto := round((p->>'monto')::numeric, 2); exception when others then v_monto := null; end;
  if v_monto is null or v_monto <= 0 then raise exception 'El monto del abono no es válido.'; end if;
  if v_metodo not in ('efectivo','transferencia','tarjeta') then raise exception 'Forma de pago inválida.'; end if;
  v_saldo := v_ap.precio - v_ap.pagado;
  if v_monto > v_saldo then
    raise exception 'El abono es mayor que lo que falta por pagar ($%).', to_char(v_saldo, 'FM999,999,990.00'); end if;
  v_tipo := case when v_monto = v_saldo then 'finiquito' else 'abono' end;

  insert into public.apartado_pagos (client_id, apartado_id, tipo, monto, metodo, ts, dia, hora, usuario, registro, registrado_por)
  values (v_cid, v_ap.id, v_tipo, v_monto, v_metodo, v_ts, v_dia, v_hora, v_yo.usuario, v_yo.nombre, auth.uid())
  returning id into v_pago;
  update public.apartados set pagado = pagado + v_monto where id = v_ap.id;

  if v_tipo = 'finiquito' then
    -- Forma de pago de la venta: la que juntó más dinero en el apartado
    select metodo into v_metv from public.apartado_pagos
     where apartado_id = v_ap.id and estado = 'ok'
     group by metodo order by sum(monto) desc, metodo limit 1;
    insert into public.ventas (client_id, ts, dia, hora, usuario, vendedor, total, metodo, recibido, cambio, registrada_por)
    values ('apartado-' || v_ap.id, v_ts, v_dia, v_hora, v_yo.usuario, v_yo.nombre, v_ap.precio, coalesce(v_metv, v_metodo),
            v_ap.precio, 0, auth.uid())
    returning folio into v_folio;
    insert into public.partidas (folio, clave, nombre, cantidad, precio, importe)
    values (v_folio, 'apartado', left('Apartado: ' || v_ap.articulo, 60), 1, v_ap.precio, v_ap.precio);
    update public.apartados set estado = 'liquidado', folio_venta = v_folio, liquidado_ts = v_ts where id = v_ap.id;
  end if;
  return jsonb_build_object('pago', v_pago, 'tipo', v_tipo, 'folio', v_folio);
end $$;

-- Cancelar un apartado que no se liquidó
create or replace function public.cancelar_apartado(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_nombre text;
begin
  select nombre into v_nombre from public.perfiles where id = auth.uid() and activo;
  if v_nombre is null then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  update public.apartados set estado = 'cancelado', cancelado_por = v_nombre, cancelado_ts = now()
   where id = p_id and estado = 'abierto';
  if not found then raise exception 'Solo se puede cancelar un apartado que sigue abierto.'; end if;
end $$;

-- Cancelar un anticipo o abono capturado por error (el apartado debe seguir abierto)
create or replace function public.cancelar_pago_apartado(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_nombre text; v_pg public.apartado_pagos%rowtype; v_estado text;
begin
  select nombre into v_nombre from public.perfiles where id = auth.uid() and activo;
  if v_nombre is null then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  select * into v_pg from public.apartado_pagos where id = p_id;
  if not found then raise exception 'No existe ese pago.'; end if;
  select estado into v_estado from public.apartados where id = v_pg.apartado_id for update;
  if v_estado <> 'abierto' then raise exception 'El apartado ya no está abierto; no se puede cambiar.'; end if;
  if v_pg.tipo = 'finiquito' then raise exception 'El finiquito no se puede cancelar.'; end if;
  update public.apartado_pagos set estado = 'cancelado', cancelado_por = v_nombre, cancelado_ts = now()
   where id = p_id and estado = 'ok';
  if found then
    update public.apartados set pagado = pagado - v_pg.monto where id = v_pg.apartado_id;
  end if;
end $$;


-- ---------- Usuarios (interno) ----------
-- Los usuarios entran con  <usuario>@caja.lacruz  (la app lo arma sola; nunca se envían correos)
create or replace function public._crear_usuario(p_usuario text, p_nombre text, p_password text)
returns void language plpgsql security definer set search_path = public, extensions as $$
declare
  v_id uuid := gen_random_uuid();
  v_email text := lower(p_usuario) || '@caja.lacruz';
begin
  if exists (select 1 from public.perfiles where usuario = lower(p_usuario)) then return; end if;
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                          confirmation_token, recovery_token, email_change_token_new, email_change,
                          email_change_token_current, phone_change, phone_change_token, reauthentication_token)
  values ('00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
          extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}', jsonb_build_object('nombre', p_nombre), now(), now(),
          '', '', '', '', '', '', '', '');
  insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (v_id::text, v_id, jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true), 'email', now(), now(), now());
  insert into public.perfiles (id, usuario, nombre) values (v_id, lower(p_usuario), p_nombre);
end $$;


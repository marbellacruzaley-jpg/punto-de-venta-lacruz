-- ---------- Funciones que usa la app ----------
create or replace function public.alta_usuario(p_usuario text, p_nombre text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.es_activo() then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if lower(coalesce(p_usuario,'')) !~ '^[a-z0-9._-]{3,30}$' then
    raise exception 'El usuario debe tener de 3 a 30 letras o números, sin espacios ni acentos.'; end if;
  if trim(coalesce(p_nombre,'')) = '' then raise exception 'Escribe el nombre que saldrá en el recibo.'; end if;
  if exists (select 1 from public.perfiles where usuario = lower(p_usuario)) then raise exception 'Ese usuario ya existe.'; end if;
  perform public._crear_usuario(lower(p_usuario), left(trim(p_nombre), 40), public._pass_inicial());
end $$;

create or replace function public.restablecer_password(p_usuario text)
returns void language plpgsql security definer set search_path = public, extensions as $$
begin
  if not public.es_activo() then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  update auth.users set encrypted_password = extensions.crypt(public._pass_inicial(), extensions.gen_salt('bf')), updated_at = now()
   where id = (select id from public.perfiles where usuario = lower(p_usuario));
end $$;

create or replace function public.activar_usuario(p_usuario text, p_activo boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.es_activo() then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if not p_activo and exists (select 1 from public.perfiles where id = auth.uid() and usuario = lower(p_usuario)) then
    raise exception 'No puedes desactivar tu propio usuario.'; end if;
  update public.perfiles set activo = p_activo where usuario = lower(p_usuario);
end $$;

create or replace function public.registrar_venta(p jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_cid    text := p->>'client_id';
  v_folio  bigint;
  v_yo     public.perfiles%rowtype;
  v_vend   public.perfiles%rowtype;
  v_total  numeric(12,2) := 0;
  v_it     jsonb;
  v_cant   integer;
  v_precio numeric(12,2);
  v_metodo text := coalesce(p->>'metodo', 'efectivo');
  v_rec    numeric(12,2);
  v_ms     bigint;
  v_ts     timestamptz := now();
begin
  select * into v_yo from public.perfiles where id = auth.uid() and activo;
  if not found then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if v_cid is null or v_cid !~ '^[A-Za-z0-9_-]{6,64}$' then raise exception 'Venta sin identificador válido.'; end if;

  -- Reintento de una venta que ya llegó (por ejemplo, enviada sin internet): se devuelve el mismo folio
  select folio into v_folio from public.ventas where client_id = v_cid;
  if found then return v_folio; end if;

  if jsonb_typeof(p->'items') is distinct from 'array' or jsonb_array_length(p->'items') = 0 then
    raise exception 'La venta no tiene productos.'; end if;
  for v_it in select * from jsonb_array_elements(p->'items') loop
    begin
      v_cant := (v_it->>'cant')::integer;
      v_precio := round((v_it->>'precio')::numeric, 2);
    exception when others then
      raise exception 'Hay un producto con cantidad o precio inválido.';
    end;
    if v_cant is null or v_cant < 1 or v_cant > 9999 or v_precio is null or v_precio <= 0 or v_precio > 1000000
       or trim(coalesce(v_it->>'nombre','')) = '' then
      raise exception 'Hay un producto con cantidad o precio inválido.'; end if;
    v_total := v_total + v_cant * v_precio;
  end loop;

  if v_metodo not in ('efectivo','transferencia','tarjeta') then raise exception 'Forma de pago inválida.'; end if;
  v_rec := case when v_metodo = 'efectivo' then round(coalesce(nullif(p->>'recibido','')::numeric, v_total), 2) else v_total end;
  if v_rec < v_total then raise exception 'El efectivo recibido es menor que el total.'; end if;

  -- Hora del celular si es razonable (ventas guardadas sin internet); si no, la del servidor
  begin v_ms := nullif(p->>'ts','')::bigint; exception when others then v_ms := null; end;
  if v_ms is not null and to_timestamp(v_ms / 1000.0) between now() - interval '7 days' and now() + interval '5 minutes' then
    v_ts := to_timestamp(v_ms / 1000.0);
  end if;

  -- Ventas hechas sin internet quedan a nombre de quien las hizo
  v_vend := v_yo;
  if coalesce(p->>'por','') <> '' and lower(p->>'por') <> v_yo.usuario then
    select * into v_vend from public.perfiles where usuario = lower(p->>'por') and activo;
    if not found then v_vend := v_yo; end if;
  end if;

  insert into public.ventas (client_id, ts, dia, hora, usuario, vendedor, total, metodo, recibido, cambio, registrada_por)
  values (v_cid, v_ts, (v_ts at time zone 'America/Mexico_City')::date, to_char(v_ts at time zone 'America/Mexico_City', 'HH24:MI'),
          v_vend.usuario, v_vend.nombre, v_total, v_metodo, v_rec, v_rec - v_total, auth.uid())
  on conflict (client_id) do nothing
  returning folio into v_folio;
  if v_folio is null then
    select folio into v_folio from public.ventas where client_id = v_cid;
    return v_folio;
  end if;

  insert into public.partidas (folio, clave, nombre, cantidad, precio, importe)
  select v_folio,
         coalesce(nullif(regexp_replace(lower(coalesce(e->>'k','otros')), '[^a-z0-9_]', '', 'g'), ''), 'otros'),
         left(trim(e->>'nombre'), 60),
         (e->>'cant')::integer,
         round((e->>'precio')::numeric, 2),
         round((e->>'cant')::integer * round((e->>'precio')::numeric, 2), 2)
    from jsonb_array_elements(p->'items') e;
  return v_folio;
end $$;

create or replace function public.cancelar_venta(p_folio bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_nombre text;
begin
  select nombre into v_nombre from public.perfiles where id = auth.uid() and activo;
  if v_nombre is null then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if not exists (select 1 from public.ventas where folio = p_folio) then raise exception 'No existe esa venta.'; end if;
  update public.ventas set estado = 'cancelada', cancelada_por = v_nombre, cancelada_ts = now()
   where folio = p_folio and estado = 'ok';
end $$;


create extension if not exists pgcrypto with schema extensions;

-- ---------- Tablas ----------
create table if not exists public.perfiles (
  id       uuid primary key references auth.users(id) on delete cascade,
  usuario  text not null unique,
  nombre   text not null,
  activo   boolean not null default true,
  creado   timestamptz not null default now()
);

create table if not exists public.ventas (
  folio          bigint generated by default as identity primary key,
  client_id      text not null unique,
  ts             timestamptz not null,
  dia            date not null,
  hora           text not null,
  usuario        text not null,
  vendedor       text not null,
  total          numeric(12,2) not null,
  metodo         text not null check (metodo in ('efectivo','transferencia','tarjeta')),
  recibido       numeric(12,2) not null,
  cambio         numeric(12,2) not null,
  estado         text not null default 'ok' check (estado in ('ok','cancelada')),
  cancelada_por  text,
  cancelada_ts   timestamptz,
  registrada     timestamptz not null default now(),
  registrada_por uuid references auth.users(id) on delete set null
);
create index if not exists ventas_dia on public.ventas(dia);

create table if not exists public.partidas (
  id        bigint generated by default as identity primary key,
  folio     bigint not null references public.ventas(folio) on delete cascade,
  clave     text not null,
  nombre    text not null,
  cantidad  integer not null check (cantidad between 1 and 9999),
  precio    numeric(12,2) not null check (precio > 0),
  importe   numeric(12,2) not null
);
create index if not exists partidas_folio on public.partidas(folio);

create table if not exists public.ajustes (
  clave        text primary key,
  valor        jsonb not null,
  actualizado  timestamptz not null default now()
);

-- ---------- Seguridad: solo usuarios activos leen; las escrituras van por funciones ----------
create or replace function public.es_activo() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfiles where id = auth.uid() and activo);
$$;


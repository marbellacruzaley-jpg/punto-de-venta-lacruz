-- ---------- Egresos (gastos) ----------
create table if not exists public.egresos (
  id              bigint generated by default as identity primary key,
  client_id       text not null unique,
  ts              timestamptz not null,
  dia             date not null,
  hora            text not null,
  categoria       text not null,
  concepto        text not null default '',
  monto           numeric(12,2) not null check (monto > 0),
  metodo          text not null check (metodo in ('efectivo','transferencia','tarjeta')),
  usuario         text not null,
  registro        text not null,
  estado          text not null default 'ok' check (estado in ('ok','cancelado')),
  cancelado_por   text,
  cancelado_ts    timestamptz,
  registrado      timestamptz not null default now(),
  registrado_por  uuid references auth.users(id) on delete set null
);
create index if not exists egresos_dia on public.egresos(dia);
alter table public.egresos enable row level security;
revoke all on public.egresos from anon;
revoke insert, update, delete, truncate on public.egresos from authenticated;
grant select on public.egresos to authenticated;
drop policy if exists leer_egresos on public.egresos;
create policy leer_egresos on public.egresos for select to authenticated using (public.es_activo());

create or replace function public.registrar_egreso(p jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_cid    text := p->>'client_id';
  v_id     bigint;
  v_yo     public.perfiles%rowtype;
  v_quien  public.perfiles%rowtype;
  v_monto  numeric(12,2);
  v_metodo text := coalesce(p->>'metodo', 'efectivo');
  v_cat    text := left(trim(coalesce(p->>'categoria','')), 40);
  v_ms     bigint;
  v_ts     timestamptz := now();
begin
  select * into v_yo from public.perfiles where id = auth.uid() and activo;
  if not found then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if v_cid is null or v_cid !~ '^[A-Za-z0-9_-]{6,64}$' then raise exception 'Gasto sin identificador válido.'; end if;
  select id into v_id from public.egresos where client_id = v_cid;
  if found then return v_id; end if;
  begin v_monto := round((p->>'monto')::numeric, 2); exception when others then v_monto := null; end;
  if v_monto is null or v_monto <= 0 or v_monto > 10000000 then raise exception 'El monto del gasto no es válido.'; end if;
  if v_cat = '' then raise exception 'Elige la categoría del gasto.'; end if;
  if v_metodo not in ('efectivo','transferencia','tarjeta') then raise exception 'Forma de pago inválida.'; end if;
  begin v_ms := nullif(p->>'ts','')::bigint; exception when others then v_ms := null; end;
  if v_ms is not null and to_timestamp(v_ms / 1000.0) between now() - interval '7 days' and now() + interval '5 minutes' then
    v_ts := to_timestamp(v_ms / 1000.0);
  end if;
  v_quien := v_yo;
  if coalesce(p->>'por','') <> '' and lower(p->>'por') <> v_yo.usuario then
    select * into v_quien from public.perfiles where usuario = lower(p->>'por') and activo;
    if not found then v_quien := v_yo; end if;
  end if;
  insert into public.egresos (client_id, ts, dia, hora, categoria, concepto, monto, metodo, usuario, registro, registrado_por)
  values (v_cid, v_ts, (v_ts at time zone 'America/Mexico_City')::date, to_char(v_ts at time zone 'America/Mexico_City', 'HH24:MI'),
          v_cat, left(trim(coalesce(p->>'concepto','')), 80), v_monto, v_metodo, v_quien.usuario, v_quien.nombre, auth.uid())
  on conflict (client_id) do nothing
  returning id into v_id;
  if v_id is null then select id into v_id from public.egresos where client_id = v_cid; end if;
  return v_id;
end $$;

create or replace function public.cancelar_egreso(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_nombre text;
begin
  select nombre into v_nombre from public.perfiles where id = auth.uid() and activo;
  if v_nombre is null then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if not exists (select 1 from public.egresos where id = p_id) then raise exception 'No existe ese gasto.'; end if;
  update public.egresos set estado = 'cancelado', cancelado_por = v_nombre, cancelado_ts = now()
   where id = p_id and estado = 'ok';
end $$;
revoke execute on function public.registrar_egreso(jsonb), public.cancelar_egreso(bigint) from public, anon;
grant execute on function public.registrar_egreso(jsonb), public.cancelar_egreso(bigint) to authenticated;

-- ---------- Corte del día ----------
-- Cada día tiene su corte (ventas, gastos y efectivo en caja); hacerlo otra vez lo actualiza.
create table if not exists public.cortes (
  dia            date primary key,
  ventas         integer not null,
  canceladas     integer not null,
  total          numeric(12,2) not null,
  efectivo       numeric(12,2) not null,
  transferencia  numeric(12,2) not null,
  tarjeta        numeric(12,2) not null,
  egresos        numeric(12,2) not null default 0,
  egresos_efectivo numeric(12,2) not null default 0,
  n_egresos      integer not null default 0,
  ultimo_folio   bigint,
  hecho_por      text not null,
  hecho_en       timestamptz not null default now(),
  veces          integer not null default 1
);
alter table public.cortes add column if not exists egresos numeric(12,2) not null default 0;
alter table public.cortes add column if not exists egresos_efectivo numeric(12,2) not null default 0;
alter table public.cortes add column if not exists n_egresos integer not null default 0;
alter table public.cortes enable row level security;
revoke all on public.cortes from anon;
revoke insert, update, delete, truncate on public.cortes from authenticated;
grant select on public.cortes to authenticated;
drop policy if exists leer_cortes on public.cortes;
create policy leer_cortes on public.cortes for select to authenticated using (public.es_activo());

create or replace function public.hacer_corte(p_dia date)
returns public.cortes language plpgsql security definer set search_path = public as $$
declare v_nombre text; v_r public.cortes;
begin
  select nombre into v_nombre from public.perfiles where id = auth.uid() and activo;
  if v_nombre is null then raise exception 'Tu sesión terminó. Vuelve a entrar.' using errcode = '28000'; end if;
  if p_dia is null or p_dia > (now() at time zone 'America/Mexico_City')::date then
    raise exception 'No se puede hacer el corte de un día que todavía no llega.'; end if;
  insert into public.cortes (dia, ventas, canceladas, total, efectivo, transferencia, tarjeta,
                             egresos, egresos_efectivo, n_egresos, ultimo_folio, hecho_por, hecho_en)
  select p_dia,
         count(*) filter (where estado = 'ok'),
         count(*) filter (where estado = 'cancelada'),
         coalesce(sum(total) filter (where estado = 'ok'), 0),
         coalesce(sum(total) filter (where estado = 'ok' and metodo = 'efectivo'), 0),
         coalesce(sum(total) filter (where estado = 'ok' and metodo = 'transferencia'), 0),
         coalesce(sum(total) filter (where estado = 'ok' and metodo = 'tarjeta'), 0),
         (select coalesce(sum(monto), 0) from public.egresos where dia = p_dia and estado = 'ok'),
         (select coalesce(sum(monto), 0) from public.egresos where dia = p_dia and estado = 'ok' and metodo = 'efectivo'),
         (select count(*) from public.egresos where dia = p_dia and estado = 'ok'),
         max(folio), v_nombre, now()
    from public.ventas where dia = p_dia
  on conflict (dia) do update set
    ventas = excluded.ventas, canceladas = excluded.canceladas, total = excluded.total,
    efectivo = excluded.efectivo, transferencia = excluded.transferencia, tarjeta = excluded.tarjeta,
    egresos = excluded.egresos, egresos_efectivo = excluded.egresos_efectivo, n_egresos = excluded.n_egresos,
    ultimo_folio = excluded.ultimo_folio, hecho_por = excluded.hecho_por, hecho_en = excluded.hecho_en,
    veces = public.cortes.veces + 1
  returning * into v_r;
  return v_r;
end $$;
revoke execute on function public.hacer_corte(date) from public, anon;
grant execute on function public.hacer_corte(date) to authenticated;

